import assert from 'node:assert/strict';
import { TextProcessor, estimateSpeechDuration, estimateScriptDuration } from '../src/lib/textProcessor.ts';
const processor = new TextProcessor();
assert.equal(estimateSpeechDuration(240, 'zh'), 60);
assert.equal(estimateSpeechDuration(150, 'en'), 60);
assert.equal(estimateSpeechDuration(240, 'zh', 2), 30);
assert.equal(estimateSpeechDuration(0, 'zh'), 0);
assert.equal(estimateSpeechDuration(-2, 'zh'), 0);
assert.equal(estimateSpeechDuration(NaN, 'zh'), 0);
assert.equal(estimateSpeechDuration(240, 'zh', 0), 60);
assert.equal(processor.detectLanguage('').language, 'unknown');
assert.equal(processor.detectTopic('人工智能算法和芯片技术'), '科技');
assert.equal(processor.getStats('你好 world!').wordCount, 3);
assert.equal(processor.getStats('Привет мир').wordCount, 2);
assert.equal(processor.getStats('こんにちは').wordCount, 5);
assert.equal(processor.getStats('مرحبا بالعالم').wordCount, 2);
const roles = [{ role_id: 'host', voice_config: { speed: 1 } }, { role_id: 'guest', voice_config: { speed: 2 } }];
const segments = [{ role_id: 'host', text: '中'.repeat(240) }, { role_id: 'guest', text: '中'.repeat(240) }];
assert.equal(estimateScriptDuration(segments, roles), 90);
assert.equal(estimateScriptDuration([{ ...segments[0], speed: 2 }], roles), 30);
assert.equal(estimateScriptDuration([{ role_id: 'host', text: '中'.repeat(240) + ' the'.repeat(150) }], roles), 120);
assert.equal(estimateScriptDuration([], roles), 0);
assert.equal(estimateScriptDuration([{ role_id: 'host', text: ' !!! ' }], roles), 0);
assert.ok(processor.getKeywords('custom custom', { topN: 1 }).length);
assert.equal(new TextProcessor({ extraStopwords: ['custom'] }).getKeywords('custom custom').length, 0);
console.log('PASS: text analysis, multilingual counts, duration rates, mixed-language totals, per-role speed, sentence overrides and empty inputs');
