import assert from 'node:assert/strict';
import { dispatch } from '../src/mocks/server.ts';
const call = async (path, method = 'GET', body, expectedStatus = 200) => {
  const response = await dispatch(new Request(`http://localhost/api${path}`, { method, headers: { 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) }));
  const json = await response.json(); assert.equal(response.status, expectedStatus, JSON.stringify(json)); return json;
};
await call('/auth/login', 'POST', { username: 'demo', password: 'TextCast123' });
const catalog = (await call('/voices')).data.voices;
assert.ok(new Set(catalog.map(v => v.tts_provider)).size > 1);
assert.ok(new Set(catalog.map(v => v.tts_model)).size > 1);
const filtered = (await call('/voices?tts_provider=mock&tts_model=demo-tts&language=zh-CN')).data.voices;
assert.equal(filtered.length, 3);
const list = (await call('/projects/project_demo_3/scripts')).data.items;
const script = (await call(`/scripts/${list[0].script_id}`)).data;
const expected = { expected_script_version: script.version, expected_edit_revision: script.edit_revision };
const body = { ...expected, title: '修改后的播客', summary: '角色声音配置演示', roles: structuredClone(script.roles), sentences: script.sentences };
body.roles[0].name = '主持人小夏'; body.roles[0].voice_config.speed = 1.2; body.roles[0].voice_config.extra_params = { volume: 0.6, emotion: 'gentle' };
const saved = (await call(`/scripts/${script.script_id}`, 'PUT', body)).data;
assert.equal(saved.roles[0].profile_id, script.roles[0].profile_id);
assert.equal(saved.edit_revision, script.edit_revision + 1);
assert.deepEqual((await call(`/scripts/${script.script_id}`)).data.roles, saved.roles);
assert.equal((await call(`/scripts/${script.script_id}`, 'PUT', body, 409)).code, 'REVISION_CONFLICT');
body.expected_edit_revision = saved.edit_revision;
const originalVoice = structuredClone(body.roles[0].voice_config);
body.roles[0].voice_config.voice_id = 'not-a-voice';
assert.equal((await call(`/scripts/${script.script_id}`, 'PUT', body, 422)).code, 'INVALID_VOICE');
body.roles[0].voice_config = { ...originalVoice, speed: 9 };
assert.equal((await call(`/scripts/${script.script_id}`, 'PUT', body, 422)).code, 'INVALID_AUDIO_PARAMS');
body.roles[0].voice_config = { ...originalVoice, extra_params: { volume: 5 } };
assert.equal((await call(`/scripts/${script.script_id}`, 'PUT', body, 422)).code, 'INVALID_AUDIO_PARAMS');
body.roles[0].voice_config = originalVoice;
const current = { expected_script_version: saved.version, expected_edit_revision: saved.edit_revision };
await call(`/scripts/${script.script_id}/confirm`, 'POST', current);
assert.equal((await call(`/scripts/${script.script_id}`, 'PUT', body, 409)).code, 'SCRIPT_LOCKED');
assert.equal((await call(`/scripts/${script.script_id}`)).data.editable, false);
await call(`/scripts/${script.script_id}/unconfirm`, 'POST', current);
assert.equal((await call(`/scripts/${script.script_id}`)).data.editable, true);
console.log('PASS: voice catalog and filters, script save and readback, role profile retention, revision conflict, invalid voice/params, confirmation lock, unconfirm');
